export function ghanaPaymentCompatibility(opportunityMethods = []) {
  // Returns { score 0-100, routes: [...], compatible: [provider ids], notes }
  const providers = defaultPaymentProviders;
  const compat = new Map(
    providers.map((p) => [p.name.toLowerCase(), p.status === 'verified' && p.ghana_signup === 'yes' ? 100 : p.status === 'needs verification' ? 50 : 10]),
  );
  const routes = [];
  for (const provider of providers) {
    const usable = provider.ghana_signup === 'yes' || provider.ghana_signup === 'reported';
    const verified = provider.status === 'verified';
    if (usable || verified) {
      routes.push({
        provider: provider.name,
        status: provider.status,
        withdraw: provider.withdraw_bank,
        momo: provider.mobile_money,
        fees: provider.fees,
        verified_date: provider.verified_date,
        source: provider.source,
      });
    }
  }
  return {
    score: 70, // MVP heuristic; refined per opportunity type in payment engine
    routes,
    channels: ['Employer → Payoneer/Deel/Remote → Ghana bank', 'Employer → market payout (Upwork/Fiverr) → Payoneer → Ghana bank/MoMo', 'Client → Paystack/Flutterwave checkout → Ghana bank/MoMo', 'Employer → SWIFT wire → Ghana FX account'],
    notes: 'Ghana receive rails verified 2026-09-19: Payoneer, Deel, Remote, Paystack, Flutterwave, Swift bank, MoMo. PayPal and direct Stripe not available for receive.',
  };
}